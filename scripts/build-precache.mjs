#!/usr/bin/env node
// Writes precache-manifest.js: the list of files the Service Worker
// precaches and a version hash of their contents. Run after changing any
// app file (npm run build). `--check` exits non-zero if the committed
// manifest is out of date (used by the test suite).

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative, sep } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'precache-manifest.js');

// The game's rules: everything single player, the server and the
// multiplayer client share. Their fingerprint goes into src/net/build.js, so
// a server and a game with different rules never play together (the server
// is always updated along with the game: docs/MULTIPLAYER.md).
const RULE_ROOTS = ['src/game', 'src/net', 'src/core', 'src/weapons', 'src/render/weapon-anim.js', 'server', 'cloud', 'data'];
const BUILD_FILE = 'src/net/build.js';

const SHELL_ROOTS = ['index.html', 'manifest.webmanifest', 'css', 'fonts', 'src', 'icons'];
const DATA_ROOTS = ['data'];
const EXTENSIONS = new Set(['.html', '.webmanifest', '.css', '.js', '.png', '.svg', '.json', '.woff2', '.mp3', '.ogg', '.wav']);

function walk(path, out) {
  const abs = join(root, path);
  if (!existsSync(abs)) return out;
  if (statSync(abs).isDirectory()) {
    for (const name of readdirSync(abs).sort()) walk(join(path, name), out);
  } else if (EXTENSIONS.has(path.slice(path.lastIndexOf('.')))) {
    out.push(path.split(sep).join('/'));
  }
  return out;
}

/** src/net/build.js: the fingerprint of the game's rules. */
export function buildInfo() {
  const files = RULE_ROOTS.flatMap((p) => walk(p, [])).filter((f) => f !== BUILD_FILE);
  const hash = createHash('sha256');
  for (const file of files) {
    hash.update(file);
    hash.update(readFileSync(join(root, file)));
  }
  const build = hash.digest('hex').slice(0, 12);
  return {
    build,
    source: '// Generated by scripts/build-precache.mjs — do not edit by hand.\n'
      + '// A fingerprint of the game\'s rules (src/game, src/net, server, data …): the\n'
      + '// server and the game only play together when theirs are the same.\n'
      + `export const BUILD = '${build}';\n`,
  };
}

export function buildManifest(info = buildInfo()) {
  const shell = SHELL_ROOTS.flatMap((p) => walk(p, []));
  const data = DATA_ROOTS.flatMap((p) => walk(p, []));
  const hash = createHash('sha256');
  for (const file of [...shell, ...data, 'sw.js']) {
    hash.update(file);
    hash.update(file === BUILD_FILE ? info.source : readFileSync(join(root, file)));
  }
  const version = hash.digest('hex').slice(0, 12);
  const body = JSON.stringify({ version, shell, data }, null, 2);
  return {
    version,
    shell,
    data,
    source: `// Generated by scripts/build-precache.mjs — do not edit by hand.\nself.__PRECACHE = ${body};\n`,
  };
}

if (process.argv[1] && relative(process.argv[1], fileURLToPath(import.meta.url)) === '') {
  const info = buildInfo();
  const buildPath = join(root, BUILD_FILE);
  // (Written first: it is one of the app's files.)
  if (!process.argv.includes('--check')) writeFileSync(buildPath, info.source);
  const manifest = buildManifest(info);
  if (process.argv.includes('--check')) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    const currentBuild = existsSync(buildPath) ? readFileSync(buildPath, 'utf8') : '';
    if (current !== manifest.source || currentBuild !== info.source) {
      console.error('precache-manifest.js or src/net/build.js is out of date. Run: npm run build');
      process.exit(1);
    }
    console.log(`precache-manifest.js is up to date (version ${manifest.version}, rules ${info.build})`);
  } else {
    writeFileSync(OUT, manifest.source);
    console.log(`precache-manifest.js written: version ${manifest.version}, ${manifest.shell.length} shell files, ${manifest.data.length} data files; rules ${info.build}`);
  }
}
