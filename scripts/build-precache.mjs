#!/usr/bin/env node
// Writes precache-manifest.js: the list of files the Service Worker
// precaches and a version hash of their contents. Run after changing any
// app file (npm run build). `--check` exits non-zero if the committed
// manifest is out of date (used by the test suite).

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative, sep } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'precache-manifest.js');

const SHELL_ROOTS = ['index.html', 'manifest.webmanifest', 'css', 'fonts', 'src', 'icons'];
const DATA_ROOTS = ['data'];
const EXTENSIONS = new Set(['.html', '.webmanifest', '.css', '.js', '.png', '.svg', '.json', '.woff2', '.mp3', '.ogg', '.wav']);

function walk(path, out) {
  const abs = join(root, path);
  if (!existsSync(abs)) return out;
  if (statSync(abs).isDirectory()) {
    for (const name of readdirSync(abs).sort()) walk(join(path, name), out);
  } else if (EXTENSIONS.has(path.slice(path.lastIndexOf('.')))) {
    out.push(path.split(sep).join('/'));
  }
  return out;
}

export function buildManifest() {
  const shell = SHELL_ROOTS.flatMap((p) => walk(p, []));
  const data = DATA_ROOTS.flatMap((p) => walk(p, []));
  const hash = createHash('sha256');
  for (const file of [...shell, ...data, 'sw.js']) {
    hash.update(file);
    hash.update(readFileSync(join(root, file)));
  }
  const version = hash.digest('hex').slice(0, 12);
  const body = JSON.stringify({ version, shell, data }, null, 2);
  return {
    version,
    shell,
    data,
    source: `// Generated by scripts/build-precache.mjs — do not edit by hand.\nself.__PRECACHE = ${body};\n`,
  };
}

if (process.argv[1] && relative(process.argv[1], fileURLToPath(import.meta.url)) === '') {
  const manifest = buildManifest();
  if (process.argv.includes('--check')) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (current !== manifest.source) {
      console.error('precache-manifest.js is out of date. Run: npm run build');
      process.exit(1);
    }
    console.log(`precache-manifest.js is up to date (version ${manifest.version})`);
  } else {
    writeFileSync(OUT, manifest.source);
    console.log(`precache-manifest.js written: version ${manifest.version}, ${manifest.shell.length} shell files, ${manifest.data.length} data files`);
  }
}
